class Flipkart {
public static void main(String[] args) {

        Flipkart.login();
        Flipkart.searchProduct();
        Flipkart.addToCart();
        Flipkart.applyCoupon();
        Flipkart.placeOrder();
        Flipkart.makePayment();
        Flipkart.trackOrder();
        Flipkart.returnProduct();
    }
    static void login() {
        System.out.println("User logged in");
    }

    static void searchProduct() {
        System.out.println("Product searched");
    }

    static void addToCart() {
        System.out.println("Product added to cart");
    }

    static void applyCoupon() {
        System.out.println("Coupon applied");
    }

    static void placeOrder() {
        System.out.println("Order placed");
    }

    static void makePayment() {
        System.out.println("Payment completed");
    }

    static void trackOrder() {
        System.out.println("Order tracked");
    }

    static void returnProduct() {
        System.out.println("Product returned");
    }

    
}