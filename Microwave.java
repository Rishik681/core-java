class Microwave {

public static void main(String[] args) {

        Microwave.openDoor();
        Microwave.placeFood();
        Microwave.closeDoor();
        Microwave.setPower();
        Microwave.setTime();
        Microwave.startCooking();
        Microwave.stopCooking();
        Microwave.removeFood();
    }
    static void openDoor() {
        System.out.println("Door opened");
    }

    static void placeFood() {
        System.out.println("Food placed inside");
    }

    static void closeDoor() {
        System.out.println("Door closed");
    }

    static void setPower() {
        System.out.println("Power level set");
    }

    static void setTime() {
        System.out.println("Cooking time set");
    }

    static void startCooking() {
        System.out.println("Cooking started");
    }

    static void stopCooking() {
        System.out.println("Cooking stopped");
    }

    static void removeFood() {
        System.out.println("Food removed");
    }

    
   
	
	
	
	}